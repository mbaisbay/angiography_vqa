"""Build a vessel-masked stenosis dataset for the S6 vessel-guided pipeline.

Motivation
----------
Stenoses are very small objects (often <1% of image area). Running a YOLO
detector on the full 512x512 angiogram means most of the input budget is spent
on empty space and ribs/catheters/spine that can't contain a stenosis. This
script uses a *trained syntax (vessel) segmentation model* as a learned
attention prior, restricting the stenosis detector's input to pixels where
vessels actually live. This is a content-aware analogue of SAHI's slicing
approach — instead of a uniform grid, we crop/mask using anatomy.

Two variants are produced side-by-side so they can be ablated:

  Variant "blackout":
      Zero out every pixel outside the (dilated) vessel mask. Original image
      dimensions preserved. Stenosis GT stays in original coordinates.
      Simpler, but wastes the input-resolution budget on black pixels.

  Variant "crop":
      Compute the bounding box of the dilated vessel mask, crop the image
      to that bbox (padded to square), and remap all stenosis GT polygons
      into the cropped coordinate system. Gives the detector effectively
      higher resolution on the vessel region. The winner in most SAHI-style
      experiments in the literature.

Mask rules
----------
  * Vessel masks are generated by running the supplied syntax model on
    every stenosis image (train, val, AND test). We deliberately use
    *predicted* masks on all splits (even train) to keep the train/test
    distribution matched — the stenosis model must learn to cope with the
    exact same vessel-mask noise it will see at inference.
  * The predicted vessel union is dilated by `dilate_px` pixels (default 20).
    This is critical: stenoses sit AT vessel boundaries, so a tight mask
    risks cropping the target itself. A tunable safety margin is essential.
  * If the syntax model finds no vessels at all in an image (rare, but
    possible on garbage frames), we fall back to the full image so the
    stenosis is never lost. These fallback cases are logged in stats.json.

Output layout (mirrors the existing stenosis/ layout from prepare_data.py)
--------------------------------------------------------------------------
    <output_dir>/
        blackout/
            images/{train,val,test}/*.png    (pixel-masked)
            labels/{train,val,test}/*.txt    (unchanged, class 0)
            data.yaml                        (1-class stenosis YAML)
        crop/
            images/{train,val,test}/*.png    (tight-cropped + square-padded)
            labels/{train,val,test}/*.txt    (remapped polygons, class 0)
            data.yaml
        vessel_masks/{train,val,test}/*.png  (debug: the dilated masks used)
        stats.json                           (per-split counts + fallbacks)

The output YAMLs are single-class (stenosis only, class 0), so they can be
handed directly to train.py/evaluate.py in the same way stenosis_only.yaml is.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Optional

import cv2
import numpy as np
import yaml
from ultralytics import YOLO

SPLITS = ["train", "val", "test"]


# ── Label I/O ────────────────────────────────────────────────────────────────

def read_yolo_seg_label(path: Path) -> list[tuple[int, np.ndarray]]:
    """Read a YOLO-seg label file and return [(class_id, polygon_xy_norm), ...].

    Polygon is returned as an (N, 2) float array of normalized xy coords.
    """
    if not path.exists():
        return []
    out = []
    with open(path, "r") as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) < 7:  # need at least cls + 3 points
                continue
            cls_id = int(parts[0])
            coords = np.array([float(x) for x in parts[1:]], dtype=np.float32)
            if coords.size % 2 != 0:
                coords = coords[:-1]
            poly = coords.reshape(-1, 2)
            out.append((cls_id, poly))
    return out


def write_yolo_seg_label(path: Path, items: list[tuple[int, np.ndarray]]) -> None:
    """Write YOLO-seg label file from [(class_id, normalized_xy_polygon), ...]."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        for cls_id, poly in items:
            if len(poly) < 3:
                continue
            coords = " ".join(f"{v:.6f}" for v in poly.reshape(-1))
            f.write(f"{cls_id} {coords}\n")


# ── Vessel mask generation ───────────────────────────────────────────────────

def predict_vessel_mask(
    model: YOLO,
    image_path: Path,
    conf: float,
    imgsz: int,
) -> Optional[np.ndarray]:
    """Run the syntax model on one image and return a binary vessel mask.

    The mask is the pixel-wise UNION of all predicted segment polygons,
    regardless of which syntax class. Shape: (H, W) uint8, values {0, 255}.
    Returns None if the model produced no masks.
    """
    results = model.predict(
        source=str(image_path),
        conf=conf,
        imgsz=imgsz,
        save=False,
        save_txt=False,
        verbose=False,
        retina_masks=True,
    )
    if not results:
        return None
    result = results[0]
    if result.masks is None or len(result.masks) == 0:
        return None

    # masks.data is (N, H', W') as torch tensor — but retina_masks=True
    # returns it at the image's native size. Sum across detections, clip.
    mask_data = result.masks.data.cpu().numpy()  # (N, H, W)
    union = (mask_data.sum(axis=0) > 0).astype(np.uint8) * 255
    return union


def dilate_mask(mask: np.ndarray, dilate_px: int) -> np.ndarray:
    """Dilate a binary mask by dilate_px pixels using an elliptical kernel."""
    if dilate_px <= 0:
        return mask
    k = 2 * dilate_px + 1
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k, k))
    return cv2.dilate(mask, kernel, iterations=1)


def mask_to_crop_bbox(mask: np.ndarray, pad_px: int = 0) -> Optional[tuple[int, int, int, int]]:
    """Return (x1, y1, x2, y2) integer crop box around non-zero mask pixels.

    pad_px is an additional safety margin added on all sides (clamped to image).
    Returns None if the mask is empty.
    """
    ys, xs = np.where(mask > 0)
    if len(xs) == 0:
        return None
    h, w = mask.shape
    x1 = max(0, int(xs.min()) - pad_px)
    y1 = max(0, int(ys.min()) - pad_px)
    x2 = min(w, int(xs.max()) + 1 + pad_px)
    y2 = min(h, int(ys.max()) + 1 + pad_px)
    if x2 <= x1 or y2 <= y1:
        return None
    return x1, y1, x2, y2


# ── Variant 1: Blackout ──────────────────────────────────────────────────────

def apply_blackout(
    image: np.ndarray,
    mask: np.ndarray,
) -> np.ndarray:
    """Zero out all pixels outside the mask. Image and mask must share H, W."""
    if mask.shape != image.shape[:2]:
        mask = cv2.resize(mask, (image.shape[1], image.shape[0]),
                          interpolation=cv2.INTER_NEAREST)
    mask_bool = mask > 0
    out = image.copy()
    if out.ndim == 3:
        out[~mask_bool] = 0
    else:
        out[~mask_bool] = 0
    return out


# ── Polygon helpers ──────────────────────────────────────────────────────────

def polygon_area(poly: np.ndarray) -> float:
    """Compute area of a polygon using the shoelace formula.

    Args:
        poly: (N, 2) array of xy coordinates (absolute or normalized).

    Returns:
        Absolute area (always >= 0).
    """
    if len(poly) < 3:
        return 0.0
    x = poly[:, 0]
    y = poly[:, 1]
    return 0.5 * abs(float(np.sum(x[:-1] * y[1:] - x[1:] * y[:-1])
                            + x[-1] * y[0] - x[0] * y[-1]))


def clip_polygon_to_rect(
    poly: np.ndarray,
    x1: float, y1: float, x2: float, y2: float,
) -> np.ndarray:
    """Clip a polygon to a rectangle using the Sutherland-Hodgman algorithm.

    This properly creates new vertices at edge intersections instead of
    collapsing existing vertices to the boundary (which np.clip does and
    which distorts polygon shapes).

    Args:
        poly: (N, 2) array of xy coordinates.
        x1, y1, x2, y2: Rectangle bounds.

    Returns:
        Clipped polygon as (M, 2) array. May have fewer or more vertices
        than the input. Empty array if the polygon is fully outside.
    """
    def _clip_edge(vertices, edge_start, edge_end):
        """Clip polygon vertices against one edge of the rectangle."""
        if len(vertices) == 0:
            return []

        # Edge normal (pointing inward)
        ex, ey = edge_end[0] - edge_start[0], edge_end[1] - edge_start[1]

        def inside(p):
            # Point is inside if it's on the left side of the directed edge
            return ex * (p[1] - edge_start[1]) - ey * (p[0] - edge_start[0]) >= 0

        def intersect(p1, p2):
            # Line-line intersection between edge and segment p1->p2
            dx, dy = p2[0] - p1[0], p2[1] - p1[1]
            denom = ex * dy - ey * dx
            if abs(denom) < 1e-12:
                return p1  # parallel, return start point
            t = (ey * (p1[0] - edge_start[0]) - ex * (p1[1] - edge_start[1])) / denom
            return [p1[0] + t * dx, p1[1] + t * dy]

        output = []
        for i in range(len(vertices)):
            current = vertices[i]
            prev = vertices[i - 1]
            curr_inside = inside(current)
            prev_inside = inside(prev)

            if curr_inside:
                if not prev_inside:
                    output.append(intersect(prev, current))
                output.append(current)
            elif prev_inside:
                output.append(intersect(prev, current))

        return output

    # Convert to list of [x, y] for the algorithm
    verts = [[float(p[0]), float(p[1])] for p in poly]

    # Clip against each of the four rectangle edges (clockwise winding).
    # With CW winding, the "left side" test correctly identifies the
    # interior of the rectangle.
    edges = [
        ([x1, y1], [x2, y1]),  # bottom edge: left to right
        ([x2, y1], [x2, y2]),  # right edge: top to bottom
        ([x2, y2], [x1, y2]),  # top edge: right to left
        ([x1, y2], [x1, y1]),  # left edge: bottom to top
    ]
    for edge_start, edge_end in edges:
        verts = _clip_edge(verts, edge_start, edge_end)
        if len(verts) == 0:
            return np.empty((0, 2), dtype=np.float32)

    return np.array(verts, dtype=np.float32)


# ── Variant 2: Crop ──────────────────────────────────────────────────────────

def apply_crop_and_remap_labels(
    image: np.ndarray,
    labels: list[tuple[int, np.ndarray]],
    crop_bbox: tuple[int, int, int, int],
    pad_to_square: bool = True,
    min_area_ratio: float = 0.1,
) -> tuple[np.ndarray, list[tuple[int, np.ndarray]], dict]:
    """Crop an image to crop_bbox, pad to square, and remap normalized polygons.

    Uses Sutherland-Hodgman polygon clipping to properly handle polygons
    that cross the crop boundary, instead of the naive np.clip approach
    which distorts polygon shapes.

    Args:
        image: HxW or HxWx3 uint8 image.
        labels: List of (class_id, polygon) where polygon is (N, 2) in
                NORMALIZED coordinates of the ORIGINAL image.
        crop_bbox: (x1, y1, x2, y2) in original-image pixel coordinates.
        pad_to_square: If True, pad shorter side with zeros so crop is square.
        min_area_ratio: Drop labels that lose more than (1 - min_area_ratio)
                        of their area to clipping. Default 0.1 means keep
                        labels that retain at least 10% of original area.

    Returns:
        (cropped_image, remapped_labels, clip_stats) — labels in NORMALIZED
        coordinates of the cropped image. clip_stats tracks distortion.
    """
    H, W = image.shape[:2]
    x1, y1, x2, y2 = crop_bbox
    cropped = image[y1:y2, x1:x2]
    ch, cw = cropped.shape[:2]

    # Pad to square
    pad_top = pad_left = 0
    if pad_to_square:
        side = max(ch, cw)
        pad_top = (side - ch) // 2
        pad_bottom = side - ch - pad_top
        pad_left = (side - cw) // 2
        pad_right = side - cw - pad_left
        if cropped.ndim == 3:
            cropped = cv2.copyMakeBorder(
                cropped, pad_top, pad_bottom, pad_left, pad_right,
                cv2.BORDER_CONSTANT, value=(0, 0, 0),
            )
        else:
            cropped = cv2.copyMakeBorder(
                cropped, pad_top, pad_bottom, pad_left, pad_right,
                cv2.BORDER_CONSTANT, value=0,
            )
    out_h, out_w = cropped.shape[:2]

    clip_stats = {"labels_in": 0, "labels_kept": 0, "labels_clipped": 0,
                  "labels_dropped_outside": 0, "labels_dropped_area": 0,
                  "area_loss_pct_sum": 0.0}

    remapped = []
    for cls_id, poly_norm in labels:
        clip_stats["labels_in"] += 1
        poly_abs = poly_norm.copy()
        poly_abs[:, 0] *= W
        poly_abs[:, 1] *= H

        # Compute original area before clipping
        orig_area = polygon_area(poly_abs)

        # Proper polygon clipping against the crop rectangle
        clipped_poly = clip_polygon_to_rect(poly_abs, x1, y1, x2, y2)

        if len(clipped_poly) < 3:
            clip_stats["labels_dropped_outside"] += 1
            continue

        # Check area loss from clipping
        clipped_area = polygon_area(clipped_poly)
        if orig_area > 0:
            area_ratio = clipped_area / orig_area
            area_loss_pct = (1.0 - area_ratio) * 100
            clip_stats["area_loss_pct_sum"] += area_loss_pct
            if area_ratio < min_area_ratio:
                clip_stats["labels_dropped_area"] += 1
                continue
            if area_loss_pct > 1.0:
                clip_stats["labels_clipped"] += 1

        # Shift into crop-local coordinates and account for padding
        poly_local = clipped_poly.copy()
        poly_local[:, 0] = poly_local[:, 0] - x1 + pad_left
        poly_local[:, 1] = poly_local[:, 1] - y1 + pad_top

        # Normalize to cropped image dimensions
        poly_out = poly_local.copy()
        poly_out[:, 0] /= out_w
        poly_out[:, 1] /= out_h

        clip_stats["labels_kept"] += 1
        remapped.append((cls_id, poly_out))

    return cropped, remapped, clip_stats


# ── Main build loop ──────────────────────────────────────────────────────────

def build_vessel_masked_dataset(
    syntax_weights: str,
    stenosis_data_dir: Path,
    output_dir: Path,
    dilate_px: int = 20,
    crop_pad_px: int = 10,
    vessel_conf: float = 0.25,
    vessel_imgsz: int = 768,
    save_debug_masks: bool = True,
) -> dict:
    """Build the masked stenosis dataset (both blackout and crop variants).

    Args:
        syntax_weights: Path to trained syntax YOLO-seg model weights.
        stenosis_data_dir: Path containing images/{train,val,test} and
                           labels/{train,val,test} in YOLO format
                           (i.e., the stenosis/ dir built by prepare_data).
        output_dir: Where to write the two variants + stats.
        dilate_px: Pixels to dilate vessel mask by before blackout/crop.
                   Too small → clips stenoses. Too large → defeats the purpose.
        crop_pad_px: Extra padding added to the crop bbox on all sides.
        vessel_conf: Confidence threshold for syntax model predictions.
                     Low on purpose — we'd rather include junk vessels than
                     miss some and crop stenoses out.
        vessel_imgsz: Inference resolution for the syntax model.
        save_debug_masks: If True, save per-image vessel masks for inspection.

    Returns:
        Stats dict.
    """
    print("=" * 64)
    print("Building vessel-masked stenosis dataset")
    print("=" * 64)
    print(f"  Syntax weights : {syntax_weights}")
    print(f"  Stenosis dir   : {stenosis_data_dir}")
    print(f"  Output dir     : {output_dir}")
    print(f"  Dilate px      : {dilate_px}")
    print(f"  Crop pad px    : {crop_pad_px}")
    print(f"  Vessel conf    : {vessel_conf}")
    print(f"  Vessel imgsz   : {vessel_imgsz}")

    model = YOLO(syntax_weights)

    blackout_dir = output_dir / "blackout"
    crop_dir = output_dir / "crop"
    masks_dir = output_dir / "vessel_masks"

    stats = {"dilate_px": dilate_px, "crop_pad_px": crop_pad_px,
             "vessel_conf": vessel_conf, "splits": {}}

    for split in SPLITS:
        img_src = stenosis_data_dir / "images" / split
        lbl_src = stenosis_data_dir / "labels" / split
        if not img_src.exists():
            print(f"\n  [{split}] SKIP — no images dir at {img_src}")
            continue

        img_files = sorted(
            list(img_src.glob("*.png")) + list(img_src.glob("*.PNG"))
        )
        print(f"\n  [{split}] Processing {len(img_files)} images")

        bo_img_dir = blackout_dir / "images" / split
        bo_lbl_dir = blackout_dir / "labels" / split
        cr_img_dir = crop_dir / "images" / split
        cr_lbl_dir = crop_dir / "labels" / split
        for d in (bo_img_dir, bo_lbl_dir, cr_img_dir, cr_lbl_dir):
            d.mkdir(parents=True, exist_ok=True)
        if save_debug_masks:
            (masks_dir / split).mkdir(parents=True, exist_ok=True)

        split_stats = Counter()

        for img_path in img_files:
            stem = img_path.stem
            image = cv2.imread(str(img_path), cv2.IMREAD_COLOR)
            if image is None:
                split_stats["unreadable"] += 1
                continue
            H, W = image.shape[:2]
            split_stats["images"] += 1

            labels = read_yolo_seg_label(lbl_src / f"{stem}.txt")
            split_stats["gt_stenoses"] += len(labels)

            # 1. Predict vessel mask
            mask = predict_vessel_mask(
                model, img_path, conf=vessel_conf, imgsz=vessel_imgsz,
            )

            if mask is None:
                # Fallback: use full image. Stenosis must not disappear.
                split_stats["fallback_no_vessels"] += 1
                mask = np.full((H, W), 255, dtype=np.uint8)

            # Resize to image size if the model returned a different resolution
            if mask.shape != (H, W):
                mask = cv2.resize(mask, (W, H), interpolation=cv2.INTER_NEAREST)

            # 2. Dilate
            dilated = dilate_mask(mask, dilate_px)

            # Sanity check: compute what fraction of each stenosis polygon
            # overlaps the dilated vessel mask. Uses rasterized polygon area.
            for _, poly_norm in labels:
                poly_abs = poly_norm.copy()
                poly_abs[:, 0] *= W
                poly_abs[:, 1] *= H
                pts = poly_abs.astype(np.int32).reshape(-1, 1, 2)
                # Rasterize the polygon to compute overlap with vessel mask
                poly_mask = np.zeros((H, W), dtype=np.uint8)
                cv2.fillPoly(poly_mask, [pts], 255)
                poly_pixels = int(np.sum(poly_mask > 0))
                if poly_pixels == 0:
                    split_stats["stenoses_outside_mask"] += 1
                    continue
                overlap_pixels = int(np.sum((poly_mask > 0) & (dilated > 0)))
                overlap_ratio = overlap_pixels / poly_pixels
                if overlap_ratio < 0.5:
                    split_stats["stenoses_outside_mask"] += 1
                    split_stats["stenoses_low_overlap"] += 1
                split_stats["stenosis_mask_overlap_sum_x1000"] += int(
                    overlap_ratio * 1000)

            if save_debug_masks:
                cv2.imwrite(str(masks_dir / split / f"{stem}.png"), dilated)

            # 3a. Blackout variant
            blackout_img = apply_blackout(image, dilated)
            cv2.imwrite(str(bo_img_dir / f"{stem}.png"), blackout_img)
            write_yolo_seg_label(bo_lbl_dir / f"{stem}.txt", labels)

            # 3b. Crop variant
            crop_bbox = mask_to_crop_bbox(dilated, pad_px=crop_pad_px)
            if crop_bbox is None:
                # Fallback: full image crop
                crop_bbox = (0, 0, W, H)
                split_stats["fallback_empty_crop"] += 1
            cropped_img, cropped_labels, cstats = apply_crop_and_remap_labels(
                image, labels, crop_bbox, pad_to_square=True,
            )
            cv2.imwrite(str(cr_img_dir / f"{stem}.png"), cropped_img)
            write_yolo_seg_label(cr_lbl_dir / f"{stem}.txt", cropped_labels)
            split_stats["crop_labels_kept"] += len(cropped_labels)
            split_stats["crop_labels_clipped"] += cstats["labels_clipped"]
            split_stats["crop_labels_dropped_outside"] += cstats["labels_dropped_outside"]
            split_stats["crop_labels_dropped_area"] += cstats["labels_dropped_area"]
            split_stats["crop_area_loss_pct_sum"] += cstats["area_loss_pct_sum"]

            # Area-ratio telemetry: how much does the crop shrink the frame?
            orig_area = H * W
            bx1, by1, bx2, by2 = crop_bbox
            crop_area = (bx2 - bx1) * (by2 - by1)
            split_stats["crop_area_ratio_sum_x1000"] += int(
                1000 * crop_area / orig_area
            )

        stats["splits"][split] = dict(split_stats)
        print(f"    Images     : {split_stats['images']}")
        print(f"    GT stenoses: {split_stats['gt_stenoses']}")
        print(f"    Kept after crop: {split_stats['crop_labels_kept']}")
        print(f"    Clipped labels (>1% area loss): "
              f"{split_stats['crop_labels_clipped']}")
        print(f"    Dropped (fully outside crop): "
              f"{split_stats['crop_labels_dropped_outside']}")
        print(f"    Dropped (<10% area retained): "
              f"{split_stats['crop_labels_dropped_area']}")
        print(f"    No-vessel fallbacks: {split_stats['fallback_no_vessels']}")
        print(f"    Stenoses <50% mask overlap: "
              f"{split_stats['stenoses_outside_mask']}")
        n_gt = split_stats["gt_stenoses"]
        if n_gt > 0:
            avg_overlap = (split_stats["stenosis_mask_overlap_sum_x1000"] /
                           n_gt) / 1000.0
            print(f"    Mean stenosis-mask overlap: {avg_overlap:.3f}")
        if split_stats["images"] > 0:
            avg_ratio = (split_stats["crop_area_ratio_sum_x1000"] /
                         split_stats["images"]) / 1000.0
            print(f"    Mean crop / orig area ratio: {avg_ratio:.3f}")
        n_clipped = split_stats["crop_labels_clipped"]
        if n_clipped > 0:
            avg_loss = split_stats["crop_area_loss_pct_sum"] / max(
                split_stats["crop_labels_kept"] + split_stats["crop_labels_dropped_area"], 1)
            print(f"    Mean polygon area loss: {avg_loss:.1f}%")

    # 4. Write dataset YAMLs (both variants are single-class stenosis)
    for variant_name, variant_dir in [("blackout", blackout_dir),
                                       ("crop", crop_dir)]:
        data_yaml = {
            "path": str(variant_dir.resolve()),
            "train": "images/train",
            "val": "images/val",
            "test": "images/test",
            "nc": 1,
            "names": {0: "stenosis"},
        }
        yaml_path = variant_dir / "data.yaml"
        with open(yaml_path, "w") as f:
            yaml.dump(data_yaml, f, default_flow_style=False, sort_keys=False)
        print(f"\n  Wrote {yaml_path}")

    # 5. Save stats
    stats_path = output_dir / "stats.json"
    stats_path.parent.mkdir(parents=True, exist_ok=True)
    with open(stats_path, "w") as f:
        json.dump(stats, f, indent=2)
    print(f"  Wrote {stats_path}")

    return stats


# ── Inference-time helper for combined evaluation ────────────────────────────

def preprocess_image_for_inference(
    image_path: Path,
    syntax_model: YOLO,
    variant: str,
    dilate_px: int = 20,
    crop_pad_px: int = 10,
    vessel_conf: float = 0.25,
    vessel_imgsz: int = 768,
) -> tuple[np.ndarray, dict]:
    """Preprocess a single image the same way the training set was built.

    Used when evaluating the stenosis model as part of the combined pipeline
    on images that don't have precomputed masks (e.g., a new unseen image).

    Returns:
        (preprocessed_image, transform_info)
        transform_info has enough data to map predicted boxes back to the
        original image coordinates (needed for the "crop" variant).
    """
    image = cv2.imread(str(image_path), cv2.IMREAD_COLOR)
    H, W = image.shape[:2]
    info = {"orig_h": H, "orig_w": W, "variant": variant}

    mask = predict_vessel_mask(syntax_model, image_path,
                               conf=vessel_conf, imgsz=vessel_imgsz)
    if mask is None:
        mask = np.full((H, W), 255, dtype=np.uint8)
        info["no_vessels_fallback"] = True
    if mask.shape != (H, W):
        mask = cv2.resize(mask, (W, H), interpolation=cv2.INTER_NEAREST)
    dilated = dilate_mask(mask, dilate_px)

    if variant == "blackout":
        out = apply_blackout(image, dilated)
        info.update({"crop_bbox": (0, 0, W, H), "pad_top": 0, "pad_left": 0,
                     "out_h": H, "out_w": W})
        return out, info

    if variant == "crop":
        crop_bbox = mask_to_crop_bbox(dilated, pad_px=crop_pad_px)
        if crop_bbox is None:
            crop_bbox = (0, 0, W, H)
        cropped, _, _ = apply_crop_and_remap_labels(image, [], crop_bbox,
                                                 pad_to_square=True)
        x1, y1, x2, y2 = crop_bbox
        ch, cw = y2 - y1, x2 - x1
        side = max(ch, cw)
        pad_top = (side - ch) // 2
        pad_left = (side - cw) // 2
        info.update({"crop_bbox": crop_bbox, "pad_top": pad_top,
                     "pad_left": pad_left, "out_h": side, "out_w": side})
        return cropped, info

    raise ValueError(f"Unknown variant: {variant}")


def remap_predictions_to_original(
    boxes_xyxy: np.ndarray,
    info: dict,
) -> np.ndarray:
    """Map predicted boxes from preprocessed image back to original coordinates.

    Args:
        boxes_xyxy: (N, 4) in the preprocessed image's pixel coordinates.
        info: The transform_info dict from preprocess_image_for_inference.

    Returns:
        (N, 4) in original image pixel coordinates.
    """
    if info["variant"] == "blackout":
        return boxes_xyxy.copy()

    # crop variant: undo square padding, then undo crop offset
    x1c, y1c, _, _ = info["crop_bbox"]
    pad_top = info["pad_top"]
    pad_left = info["pad_left"]
    out = boxes_xyxy.copy().astype(np.float64)
    out[:, [0, 2]] -= pad_left
    out[:, [1, 3]] -= pad_top
    out[:, [0, 2]] += x1c
    out[:, [1, 3]] += y1c
    return out


